#!/bin/bash
# metaschedule_paper1.sh — submit the whole paper-1 PRELES rerun as a small number of
# serial chains, instead of 100 hand-driven sbatch calls.
#
# The rerun exists because the normalisation fix (commit ce79dc8e2) invalidated the
# published paper-1 results. The series varies training-data size two ways: number of
# training years (the len* CV files) and temporal sparsity (every Nth day: 50/30/7).
#
# Shape of the matrix: 20 experiments x 5 architectures = 100 experiments / 440 fold-jobs.
#
#   Station 5  (temporal lane)  len1,2,3,5 full + len1 x {50,30,7}   6 folds each
#   Station 12 (temporal lane)  len1,2,3   full + len1 x {50,30,7}   3 folds each
#   OOD        (spatial  lane)  len3,6,9,12 full + len3 x {50,30,7}  4 folds each
#
# Pacing: one serial chain per architecture, each experiment held behind the previous
# one with --dependency=afterany. Concurrency is therefore 5 chains x THROTTLE GPUs,
# not 440 queued jobs. THROTTLE is the per-experiment %N array throttle.
#
# Usage:
#   DRY_RUN=1 bash batch_scripts/metaschedule_paper1.sh     # print the plan, submit nothing
#   bash batch_scripts/metaschedule_paper1.sh               # submit
#   ARCHS="naive residual" bash batch_scripts/metaschedule_paper1.sh
#   THROTTLE=4 bash batch_scripts/metaschedule_paper1.sh
#   SKIP_PREFLIGHT=1 bash batch_scripts/metaschedule_paper1.sh
#
# Every submission is recorded in log/paper1_manifest_<timestamp>.tsv so a job id from
# sacct can be traced back to its experiment, and an experiment to its log files.

set -euo pipefail

cd "$(dirname "$0")/.."

ARCHS="${ARCHS:-naive bias parallel regularized residual}"
THROTTLE="${THROTTLE:-2}"
WORKERS_PER_FOLD="${WORKERS_PER_FOLD:-8}"
PROCESS_MODEL="${PROCESS_MODEL:-preles}"
DRY_RUN="${DRY_RUN:-0}"
SKIP_PREFLIGHT="${SKIP_PREFLIGHT:-0}"
EXCLUDE_NODES="${EXCLUDE_NODES-dlc2gpu07}"

# Capital-P is the authoritative paper-1 set: its CV_station_* files use numeric station
# indices, which resolve to the PRELES station_N.csv data. The lowercase copies use
# FLUXNET site codes and would load the newer BASFOR-era station_<CODE>__flx.csv files.
CV_DIR="configs/CV_splits/Paper_1_preles_ncvs"

# lane|cv file|sparsity   (empty sparsity = full resolution)
MANIFEST=(
    # --- Station 5: full at every available length, sparsity sweep on the shortest ---
    "temporal|temporal_cv_train_len1_station_5.json|"
    "temporal|temporal_cv_train_len2_station_5.json|"
    "temporal|temporal_cv_train_len3_station_5.json|"
    "temporal|temporal_cv_train_len5_station_5.json|"
    "temporal|temporal_cv_train_len1_station_5.json|50"
    "temporal|temporal_cv_train_len1_station_5.json|30"
    "temporal|temporal_cv_train_len1_station_5.json|7"
    # --- Station 12 ---
    "temporal|new_temporal_cv_train_len1_station_12.json|"
    "temporal|new_temporal_cv_train_len2_station_12.json|"
    "temporal|new_temporal_cv_train_len3_station_12.json|"
    "temporal|new_temporal_cv_train_len1_station_12.json|50"
    "temporal|new_temporal_cv_train_len1_station_12.json|30"
    "temporal|new_temporal_cv_train_len1_station_12.json|7"
    # --- OOD (leave-one-station-out), sparsity sweep on len3 ---
    "spatial|CV_station_len3_config.json|"
    "spatial|CV_station_len6_config.json|"
    "spatial|CV_station_len9_config.json|"
    "spatial|CV_station_len12_config.json|"
    "spatial|CV_station_len3_config.json|50"
    "spatial|CV_station_len3_config.json|30"
    "spatial|CV_station_len3_config.json|7"
)

# Short, stable tag for job names and logs: st5_len1, st12_len3, ood_len9.
experiment_tag() {
    local cv_file="$1" len group
    len=$(echo "$cv_file" | grep -oE 'len[0-9]+' | head -1)
    case "$cv_file" in
        *station_5.json)    group="st5"  ;;
        *station_12.json)   group="st12" ;;
        *station_14.json)   group="st14" ;;
        CV_station_*)       group="ood"  ;;
        *)                  group="cv"   ;;
    esac
    echo "${group}_${len}"
}

mkdir -p log
STAMP=$(date +%Y%m%d_%H%M%S)
MANIFEST_TSV="log/paper1_manifest_${STAMP}.tsv"

echo "=============================================================================="
echo " Paper-1 PRELES rerun"
echo "=============================================================================="
echo "Architectures:   $ARCHS"
echo "Experiments:     ${#MANIFEST[@]} per architecture"
echo "CV directory:    $CV_DIR"
echo "Throttle:        $THROTTLE concurrent GPUs per experiment"
echo "Workers/fold:    $WORKERS_PER_FOLD"
echo "Process model:   $PROCESS_MODEL"
echo "Manifest:        $MANIFEST_TSV"
[ "$DRY_RUN" = "1" ] && echo "Mode:            DRY RUN (nothing will be submitted)"
echo ""

# --- Preflight: frozen configs -------------------------------------------------------
# The frozen configs are regenerated by hand, so report every missing one at once rather
# than letting 100 array jobs each discover the problem separately.
# Existence is not enough: configs/config_spatial/ still holds pre-normalisation-fix
# files (naive_sparse{7,30,50}, parallel, regularized, error) that point at
# /home/.../Data instead of /work and carry no calibration:: keys. Running one would
# silently write to the wrong tree, so the modern marker keys are required too.
#
# A DRY_RUN only warns about these, so the plan stays inspectable while the configs are
# still being regenerated; a real submission refuses to proceed.
echo "--- Checking frozen configs ---"
needed_configs=()
for arch in $ARCHS; do
    for row in "${MANIFEST[@]}"; do
        IFS='|' read -r _lane _cv sp <<< "$row"
        needed_configs+=("configs/config_spatial/${arch}${sp:+_sparse${sp}}.json")
    done
done

bad_configs=$(printf '%s\n' "${needed_configs[@]}" | sort -u | python -c '
import json, sys
for path in (l.strip() for l in sys.stdin if l.strip()):
    try:
        cfg = json.load(open(path))
    except FileNotFoundError:
        print(f"MISSING  {path}"); continue
    except json.JSONDecodeError as exc:
        print(f"INVALID  {path} ({exc})"); continue
    absent = [k for k in ("calibration::root", "process_model::name") if k not in cfg]
    if absent:
        print("LEGACY   %s (no %s)" % (path, ", ".join(absent)))
')

if [ -n "$bad_configs" ]; then
    echo "$bad_configs" | sed 's/^/  /'
    echo ""
    n_bad=$(echo "$bad_configs" | wc -l)
    if [ "$DRY_RUN" = "1" ]; then
        echo "  [WARNING] $n_bad frozen config(s) missing or pre-dating the normalisation fix."
        echo "            LEGACY files exist but point at the old /home data paths and carry"
        echo "            no calibration:: keys. Regenerate with Config_Files/create_frozen_config.py."
        echo "            Continuing anyway because this is a dry run."
    else
        echo "[ERROR] $n_bad frozen config(s) missing or pre-dating the normalisation fix."
        echo "        Regenerate them with Config_Files/create_frozen_config.py, then re-run."
        echo "        (LEGACY files exist but point at the old /home data paths.)"
        echo "        Re-run with DRY_RUN=1 to inspect the plan without this check blocking."
        exit 1
    fi
else
    echo "  all present and current."
fi
echo ""

# --- Preflight: calibration bundles --------------------------------------------------
# Calibration bundles key on the train stations only, and carry no architecture in their
# path, so they are shared across all five architectures: check once per (cv, sparsity).
declare -A SKIP=()     # explicit init: under set -u an empty, never-assigned array reads as unbound
if [ "$SKIP_PREFLIGHT" != "1" ]; then
    echo "--- Checking calibration bundles (shared across architectures) ---"
    for row in "${MANIFEST[@]}"; do
        IFS='|' read -r _lane cv sp <<< "$row"
        args=(--cv-config "${CV_DIR}/${cv}")
        [ -n "$sp" ] && args+=(--sparsity "$sp")
        if ! out=$(python Utilityscripts/preflight_calibrations.py "${args[@]}" 2>&1); then
            n=$(echo "$out" | grep -oE '[0-9]+ missing' | head -1)
            echo "  SKIP  ${cv} [${sp:-full}] — ${n:-bundles missing}"
            SKIP["$row"]=1
        fi
    done
    if (( ${#SKIP[@]} == 0 )); then
        echo "  all present."
    else
        echo ""
        echo "  ${#SKIP[@]} experiment(s) will be skipped. Run their calibrations, then"
        echo "  submit only those experiments (submit_paper1.sh). Re-running this whole script"
        echo "  resubmits everything, and partially finished folds add another n_trials."
    fi
    echo ""
fi

n_runnable=$(( ${#MANIFEST[@]} - ${#SKIP[@]} ))
if (( n_runnable == 0 )); then
    echo "[ERROR] Nothing runnable after preflight."
    exit 1
fi

echo "--- Submitting: $n_runnable experiment(s) x $(echo "$ARCHS" | wc -w) architecture(s) ---"
echo ""

printf 'job_id\tjob_name\tarch\tlane\tcv_file\tsparsity\tconfig_file\tdepends_on\n' > "$MANIFEST_TSV"

JID_FILE=$(mktemp)
trap 'rm -f "$JID_FILE"' EXIT

total=0
for arch in $ARCHS; do
    echo "=== chain: $arch ==="
    prev=""
    for row in "${MANIFEST[@]}"; do
        [ -n "${SKIP[$row]:-}" ] && continue
        IFS='|' read -r lane cv sp <<< "$row"

        tag=$(experiment_tag "$cv")
        job_name="p1_${arch}_${tag}_${sp:+sparse}${sp:-full}"
        cfg="configs/config_spatial/${arch}${sp:+_sparse${sp}}.json"

        DEPEND_ON="$prev" \
        LANE="$lane" \
        CV_CONFIG_PATH="${CV_DIR}/${cv}" \
        SPARSITY="$sp" \
        prediction_loss="$arch" \
        PROCESS_MODEL="$PROCESS_MODEL" \
        WORKERS_PER_FOLD="$WORKERS_PER_FOLD" \
        THROTTLE="$THROTTLE" \
        EXCLUDE_NODES="$EXCLUDE_NODES" \
        JOB_NAME="$job_name" \
        JID_OUT="$JID_FILE" \
        DRY_RUN="$DRY_RUN" \
            bash batch_scripts/submit_paper1.sh

        jid=$(cat "$JID_FILE")
        printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
            "$jid" "$job_name" "$arch" "$lane" "$cv" "${sp:-full}" "$cfg" "${prev:-none}" \
            >> "$MANIFEST_TSV"

        # Chain: the next experiment in this architecture waits for this one. afterany,
        # so a failed experiment does not strand everything behind it.
        prev="$jid"
        total=$(( total + 1 ))
    done
    echo ""
done

echo "=============================================================================="
echo "$total submission(s) recorded in $MANIFEST_TSV"
if [ "$DRY_RUN" = "1" ]; then
    echo "DRY RUN — nothing was submitted."
else
    echo ""
    echo "Monitor:        squeue -u \$USER"
    echo "Trace a job id: grep <jobid> $MANIFEST_TSV"
    echo "Logs for a run: log/<job_name>.*.{out,err}"
    echo "Worker logs:    log/<job_name>.<arrayjobid>.<task>_workers/worker<N>.err"
fi
echo "=============================================================================="
